package kalita.plugin.apibank

import io.kotest.matchers.collections.shouldHaveSize
import io.kotest.matchers.shouldBe
import io.kotest.matchers.shouldNotBe
import kalita.plugin.api.BankTransaction
import kalita.plugin.api.Plugin
import kalita.plugin.api.StatementImporter
import kotlinx.coroutines.test.runTest
import org.junit.jupiter.api.Test
import org.junit.jupiter.params.ParameterizedTest
import org.junit.jupiter.params.provider.ValueSource
import java.io.File
import java.math.BigDecimal
import java.time.LocalDate
import java.util.ServiceLoader

/**
 * Both fixtures are synthetic exports with made-up names and amounts, generated by LibreOffice in
 * the same layout as the real "AccountData_Transactions_*.xls": `statement-text.xls` has every
 * cell as text (what the bank actually writes), `statement-typed.xls` has LibreOffice's guessed
 * numeric/date cells (the `NUMBER`/`RK` path). The real file additionally uses inline `LABEL`
 * records rather than the shared-string table LibreOffice writes — covered by [Biff8Test].
 */
class ApiBankStatementPluginTest {
    private fun fixture(name: String): ByteArray = checkNotNull(javaClass.getResourceAsStream("/$name")) { name }.readBytes()

    @Test
    fun `is registered as a built-in plugin and claims xls`() {
        val plugin = ServiceLoader.load(Plugin::class.java).filterIsInstance<ApiBankStatementPlugin>().single()
        (plugin as StatementImporter).supportedExtensions shouldBe setOf("xls")
    }

    @ParameterizedTest
    @ValueSource(strings = ["statement-text.xls", "statement-typed.xls"])
    fun `parses the header block and every table line`(name: String) {
        val statement = ApiBankStatementParser.parse(readXlsFirstSheet(fixture(name)))

        statement.clientName shouldBe "IVAN TESTOV"
        statement.accountNumber shouldBe "375-0000000000001-11RSD"
        statement.accountCurrency shouldBe "RSD"
        statement.from shouldBe LocalDate.of(2026, 11, 1)
        statement.to shouldBe LocalDate.of(2026, 11, 10)
        statement.lines shouldHaveSize 6
        statement.lines[0] shouldBe StatementLine(
            LocalDate.of(2026, 11, 9), null, "MAXI 123, BEOGRAD", "Executed", BigDecimal("-1650.00"), "RSD", BigDecimal("-1650.00"),
        )
        statement.lines[3].amount shouldBe BigDecimal("12345.67")
        statement.lines[4].status shouldBe "Reserved"
        statement.lines[5].amount shouldBe BigDecimal("-0.11")
    }

    @Test
    fun `turns lines into bank transactions with stable, distinct ids`() = runTest {
        val plugin = ApiBankStatementPlugin()

        val first = plugin.import(fixture("statement-text.xls"), "statement.xls")
        val again = plugin.import(fixture("statement-text.xls"), "statement.xls")

        first shouldHaveSize 6
        first.map { it.externalId } shouldBe again.map { it.externalId }
        first.map { it.externalId }.toSet() shouldHaveSize 6
        // Two identical purchases on one day stay two transactions (FR-B6 needs the ordinal).
        first[0].externalId shouldNotBe first[1].externalId
        first[0].bankAccount shouldBe "IVAN TESTOV"
        first[0].currency shouldBe "RSD"
        first[0].source shouldBe "import-apibank"
        first[0].merchant shouldBe "MAXI 123"
        first[0].amount shouldBe BigDecimal("-1650.00")
        first[0].status shouldBe BankTransaction.Status.Posted
        first[4].status shouldBe BankTransaction.Status.Pending
        first[5].merchant shouldBe "Konverzijska naknada: SHEIN.COM"
    }

    @Test
    fun `amount and date cells are accepted as text or as numbers`() {
        ApiBankStatementParser.parseAmount("-16,835.00") shouldBe BigDecimal("-16835.00")
        ApiBankStatementParser.parseAmount("-0.00") shouldBe BigDecimal("0.00")
        ApiBankStatementParser.parseAmount(1650.0) shouldBe BigDecimal("1650.00")
        ApiBankStatementParser.parseAmount("n/a") shouldBe null
        ApiBankStatementParser.parseDate("11/09/2026") shouldBe LocalDate.of(2026, 11, 9)
        ApiBankStatementParser.parseDate(46335.0) shouldBe LocalDate.of(2026, 11, 9)
        ApiBankStatementParser.parseDate("yesterday") shouldBe null
    }

    /** Opt-in check against real exports kept outside the repository (personal data): `-Dkalita.apibank.sample=/a.xls;/b.xls`. */
    @Test
    fun `optional real exports parse`() = runTest {
        val paths = System.getProperty("kalita.apibank.sample")?.split(';')?.filter { it.isNotBlank() } ?: return@runTest
        for (path in paths) {
            val statement = ApiBankStatementParser.parse(readXlsFirstSheet(File(path).readBytes()))
            val transactions = ApiBankStatementPlugin().toTransactions(statement)
            println("real export ${File(path).name}: account=${statement.accountNumber} ${statement.from}..${statement.to}, ${transactions.size} transactions, currencies ${transactions.map { it.currency }.toSet()}, posted=${transactions.count { it.status == BankTransaction.Status.Posted }}, sum=${transactions.sumOf { it.amount }}")
            transactions.map { it.externalId }.toSet() shouldHaveSize transactions.size
            statement.lines.size shouldBe transactions.size
        }
    }
}
