import com.healthmarketscience.jackcess.*;
import java.io.*; import java.nio.charset.StandardCharsets; import java.util.*;

/**
 * Writes modules/storage-mdb/src/main/resources/kalita/storage/mdb/xcash-2.1-extra-tables.tsv: the tables a
 * pristine X-Cash 2.1.1.54 Data.mdb has but older (2.0-era) databases lack, with seed rows for the small lookups.
 * usage: java ExportXCashExtraTables.java <pristine Data.mdb> <older Data.mdb> <out.tsv>
 * Needs the vendor database, so it is a maintainer script, not part of the build.
 */
public class ExportXCashExtraTables {
  static final Set<String> NO_SEED = Set.of("_DeletedObjects", "_ObjectsReports");
  static String esc(Object v) {
    if (v == null) return "\\N";
    String s = v instanceof java.time.LocalDateTime ? v.toString() : String.valueOf(v);
    return s.replace("\\", "\\\\").replace("\t", "\\t").replace("\r", "\\r").replace("\n", "\\n");
  }
  public static void main(String[] a) throws Exception {
    try (Database ref = new DatabaseBuilder(new File(a[0])).setReadOnly(true).open();
         Database old = new DatabaseBuilder(new File(a[1])).setReadOnly(true).setIgnoreBrokenSystemCatalogIndex(true).open();
         PrintWriter out = new PrintWriter(new OutputStreamWriter(new FileOutputStream(a[2]), StandardCharsets.UTF_8))) {
      ref.setDateTimeType(DateTimeType.LOCAL_DATE_TIME);
      Set<String> have = new HashSet<>();
      for (Row r : old.getSystemTable("MSysObjects")) have.add(String.valueOf(r.get("Name")).trim().toLowerCase());
      out.println("# SPDX-" + "FileCopyrightText: 2026 Oleg Ekhlakov <o.ekhlakov@protonmail.com>");
      out.println("# SPDX-" + "License-Identifier: GPL-3.0-only");
      out.println("# Generated by tools/mdb-research/jackcess/ExportXCashExtraTables.java - do not edit.");
      out.println("# T name | C name type size auto | I name pk|plain cols | R values (\\N = null)");
      for (String n : new TreeSet<>(ref.getTableNames())) {
        if (have.contains(n.trim().toLowerCase())) {
          Table o = old.getTable(n);
          if (o == null) continue;
          Set<String> present = new HashSet<>();
          for (Column c : o.getColumns()) present.add(c.getName().toLowerCase());
          for (Column c : ref.getTable(n).getColumns()) {
            if (present.contains(c.getName().toLowerCase())) continue;
            int size = c.getType() == DataType.TEXT ? c.getLengthInUnits() : 0;
            out.println("A\t" + n + "\t" + c.getName() + "\t" + c.getType() + "\t" + size);
          }
          continue;
        }
        Table t = ref.getTable(n);
        out.println("T\t" + n);
        for (Column c : t.getColumns()) {
          int size = c.getType() == DataType.TEXT ? c.getLengthInUnits() : 0;
          out.println("C\t" + c.getName() + "\t" + c.getType() + "\t" + size + "\t" + (c.isAutoNumber() ? 1 : 0));
        }
        for (Index i : t.getIndexes()) {
          StringBuilder cols = new StringBuilder();
          for (Index.Column ic : i.getColumns()) cols.append(cols.length() > 0 ? "," : "").append(ic.getName());
          out.println("I\t" + i.getName() + "\t" + (i.isPrimaryKey() ? "pk" : "plain") + "\t" + cols);
        }
        if (!NO_SEED.contains(n)) for (Row r : t) {
          StringBuilder sb = new StringBuilder("R");
          for (Column c : t.getColumns()) sb.append('\t').append(esc(r.get(c.getName())));
          out.println(sb);
        }
      }
    }
  }
}
